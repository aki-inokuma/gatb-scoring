/** 粗点 → 換算点（単一列の検査） */
export function lookupSimple(code: string, raw: number): number | null {
  const table = SIMPLE_TABLES[code]
  if (!table) return null
  const v = table[raw]
  return v !== undefined ? v : null
}

/** 粗点 → 換算点（複数列の検査: col = 'G' | 'V' | 'N' | 'S'） */
export function lookupMulti(code: string, raw: number, col: string): number | null {
  const table = MULTI_TABLES[code]
  if (!table) return null
  const row = table[raw]
  if (!row) return null
  return row[col] !== undefined ? row[col] : null
}

/** 主表示用の換算点（multi テーブルは最初の列を返す） */
export function lookupPrimary(code: string, raw: number): number | null {
  if (SIMPLE_TABLES[code]) return lookupSimple(code, raw)
  if (MULTI_TABLES[code]) {
    const table = MULTI_TABLES[code]
    const row = table[raw]
    if (!row) return null
    return Object.values(row)[0]
  }
  return null
}
